    code="$(curl -k -s -o /dev/null -w '%{http_code}' -m 15 "https://127.0.0.1:${port}/" 2>/dev/null || echo 000)"
    if [[ "${code}" == "200" || "${code}" == "302" ]]; then
      ok "health :${port} -> HTTP ${code}"
    else
      warn "health :${port} -> HTTP ${code}"
      bad=1
    fi
  done
  return "${bad}"
}

